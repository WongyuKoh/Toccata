def set_spec(iid, key, val):
    tgt = EXTRA.get(iid) or O.setdefault(iid, {})
    if "specs" not in tgt:
        base = json.load(open(os.path.join(F, "data.json"), encoding="utf-8"))
        tgt["specs"] = next(i["specs"] for i in base["items"] if i["id"] == iid)
    for row in tgt["specs"]:
        if row[0] == key: row[1] = val; break
    else: tgt["specs"].append([key, val])
